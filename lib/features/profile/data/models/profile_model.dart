import '../../domain/entities/profile_entity.dart';

class ProfileModel extends ProfileEntity {
  const ProfileModel({
    required super.uid,
    required super.displayName,
    required super.email,
    super.bio,
    super.avatarUrl,
    super.coverUrl,
    super.statusText,
    super.profileMusicUrl,
    super.profileMusicDurationMs,
    super.profileMusicSizeBytes,
    super.country,
    super.city,
    super.address,
    super.profession,
    super.experiences,
    super.socialLinks,
    super.verified,
    super.visibility,
    super.accountType,
    super.usernameColor,
    super.usernameFontSize,
    super.usernameFontFamily,
    super.messageFontFamily,
    super.messageColor,
    super.statusFontSize,
    super.statusBold,
    super.statusItalic,
    super.statusColor,
    super.animatedAvatarUrl,
    super.avatarFrameKey,
    super.usernameTemplateKey,
    super.usernameEffect,
    super.usernameBackgroundKey,
    super.usernameBackgroundMode,
    super.usernameBackgroundColor1,
    super.usernameBackgroundColor2,
    super.usernameBackgroundOpacity,
    super.usernameBackgroundExternalEffect,
    required super.createdAt,
    required super.updatedAt,
  });

  factory ProfileModel.fromMap(String uid, Map<String, dynamic> map) {
    return ProfileModel(
      uid: uid,
      displayName: map['displayName'] as String? ?? '',
      email: map['email'] as String? ?? '',
      bio: map['bio'] as String? ?? '',
      avatarUrl: map['avatarUrl'] as String?,
      coverUrl: map['coverUrl'] as String?,
      statusText: map['statusText'] as String?,
      profileMusicUrl: map['profileMusicUrl'] as String?,
      profileMusicDurationMs: (map['profileMusicDurationMs'] as num?)?.toInt(),
      profileMusicSizeBytes: (map['profileMusicSizeBytes'] as num?)?.toInt(),
      country: map['country'] as String?,
      city: map['city'] as String?,
      address: map['address'] as String?,
      profession: map['profession'] as String?,
      experiences: List<String>.from(map['experiences'] as List? ?? []),
      socialLinks: ((map['socialLinks'] as List?) ?? [])
          .map((e) => SocialLink.fromMap(Map<String, dynamic>.from(e as Map)))
          .toList(),
      verified: map['verified'] as bool? ?? false,
      visibility: ProfileVisibilityX.fromWire(map['visibility'] as String?),
      accountType: AccountTypeX.fromWire(map['accountType'] as String?),
      usernameColor: map['usernameColor'] as int?,
      usernameFontSize: (map['usernameFontSize'] as num?)?.toDouble() ?? 12,
      usernameFontFamily: map['usernameFontFamily'] as String? ?? '',
      messageFontFamily: map['messageFontFamily'] as String? ?? '',
      messageColor: (map['messageColor'] as num?)?.toInt() ?? 4294967295,
      statusFontSize: (map['statusFontSize'] as num?)?.toDouble() ?? 12.5,
      statusBold: map['statusBold'] as bool? ?? false,
      statusItalic: map['statusItalic'] as bool? ?? false,
      statusColor: map['statusColor'] as int?,
      animatedAvatarUrl: map['animatedAvatarUrl'] as String?,
      avatarFrameKey: map['avatarFrameKey'] as String?,
      usernameTemplateKey: map['usernameTemplateKey'] as String?,
      usernameEffect: map['usernameEffect'] as String? ?? 'none',
      usernameBackgroundKey: map['usernameBackgroundKey'] as String?,
      usernameBackgroundMode: map['usernameBackgroundMode'] as String?,
      usernameBackgroundColor1: map['usernameBackgroundColor1'] as String?,
      usernameBackgroundColor2: map['usernameBackgroundColor2'] as String?,
      usernameBackgroundOpacity: (map['usernameBackgroundOpacity'] as num?)?.toDouble() ?? .82,
      usernameBackgroundExternalEffect: map['usernameBackgroundExternalEffect'] as String?,
      createdAt: _parseDate(map['createdAt']) ?? DateTime.now(),
      updatedAt: _parseDate(map['updatedAt']) ?? DateTime.now(),
    );
  }

  factory ProfileModel.fromEntity(ProfileEntity entity) {
    return ProfileModel(
      uid: entity.uid,
      displayName: entity.displayName,
      email: entity.email,
      bio: entity.bio,
      avatarUrl: entity.avatarUrl,
      coverUrl: entity.coverUrl,
      statusText: entity.statusText,
      profileMusicUrl: entity.profileMusicUrl,
      profileMusicDurationMs: entity.profileMusicDurationMs,
      profileMusicSizeBytes: entity.profileMusicSizeBytes,
      country: entity.country,
      city: entity.city,
      address: entity.address,
      profession: entity.profession,
      experiences: entity.experiences,
      socialLinks: entity.socialLinks,
      verified: entity.verified,
      visibility: entity.visibility,
      accountType: entity.accountType,
      usernameColor: entity.usernameColor,
      usernameFontSize: entity.usernameFontSize,
      usernameFontFamily: entity.usernameFontFamily,
      messageFontFamily: entity.messageFontFamily,
      messageColor: entity.messageColor,
      statusFontSize: entity.statusFontSize,
      statusBold: entity.statusBold,
      statusItalic: entity.statusItalic,
      statusColor: entity.statusColor,
      animatedAvatarUrl: entity.animatedAvatarUrl,
      avatarFrameKey: entity.avatarFrameKey,
      usernameTemplateKey: entity.usernameTemplateKey,
      usernameEffect: entity.usernameEffect,
      usernameBackgroundKey: entity.usernameBackgroundKey,
      usernameBackgroundMode: entity.usernameBackgroundMode,
      usernameBackgroundColor1: entity.usernameBackgroundColor1,
      usernameBackgroundColor2: entity.usernameBackgroundColor2,
      usernameBackgroundOpacity: entity.usernameBackgroundOpacity,
      usernameBackgroundExternalEffect: entity.usernameBackgroundExternalEffect,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
    );
  }

  static DateTime? _parseDate(dynamic value) {
    if (value is DateTime) return value;
    final dynamic candidate = value;
    try {
      final parsed = candidate?.toDate();
      if (parsed is DateTime) return parsed;
    } catch (_) {}
    if (value is String) return DateTime.tryParse(value);
    return null;
  }

  Map<String, dynamic> toMap({bool isCreate = false}) {
    return {
      'displayName': displayName,
      'email': email,
      'bio': bio,
      'avatarUrl': avatarUrl,
      'coverUrl': coverUrl,
      'statusText': statusText,
      'profileMusicUrl': profileMusicUrl,
      'profileMusicDurationMs': profileMusicDurationMs,
      'profileMusicSizeBytes': profileMusicSizeBytes,
      'country': country,
      'city': city,
      'profession': profession,
      'experiences': experiences,
      'socialLinks': socialLinks.map((e) => e.toMap()).toList(),
      'verified': verified,
      'visibility': visibility.wire,
      'accountType': accountType.wire,
      'usernameColor': usernameColor,
      'usernameFontSize': usernameFontSize,
      'usernameFontFamily': usernameFontFamily,
      'messageFontFamily': messageFontFamily,
      'messageColor': messageColor,
      'statusFontSize': statusFontSize,
      'statusBold': statusBold,
      'statusItalic': statusItalic,
      'statusColor': statusColor,
      'animatedAvatarUrl': animatedAvatarUrl,
      'avatarFrameKey': avatarFrameKey,
      'usernameTemplateKey': usernameTemplateKey,
      'usernameEffect': usernameEffect,
      'usernameBackgroundKey': usernameBackgroundKey,
      'createdAt': createdAt.toUtc().toIso8601String(),
      'updatedAt': updatedAt.toUtc().toIso8601String(),
    };
  }
}
